-- ===================================================================
-- T. 触发器函数与触发器
-- 说明: 
-- 在 PostgreSQL 中, 触发器逻辑被封装在特殊的“触发器函数”中
-- 需要首先定义一个函数来描述“做什么”, 然后创建一个触发器来规定“何时做”
-- ===================================================================

-- -------------------------------------------------------------------
-- T.1: 自动维护标签的使用次数 (usage_count)
-- -------------------------------------------------------------------

-- 函数: update_tag_usage_count()
-- 职责: 这是一个通用的计数器函数当被触发时, 它会检查操作类型（是插入还是删除）, 
--        并相应地增加或减少 `tags` 表中对应标签的 `usage_count` 字段
--        这确保了标签的热度统计总是实时准确的
CREATE OR REPLACE FUNCTION update_tag_usage_count()
RETURNS TRIGGER AS $$
BEGIN
    -- 判断触发操作的类型
    IF (TG_OP = 'INSERT') THEN
        -- 如果是插入新关系, 则将对应 tag_id 的使用次数 +1
        UPDATE tags SET usage_count = usage_count + 1 WHERE tag_id = NEW.tag_id;
    ELSIF (TG_OP = 'DELETE') THEN
        -- 如果是删除关系, 则将对应 tag_id 的使用次数 -1
        UPDATE tags SET usage_count = usage_count - 1 WHERE tag_id = OLD.tag_id;
    END IF;
    RETURN NULL; -- 对于 AFTER 触发器, 返回值通常是 NULL, 因为它不修改正在操作的行
END;
$$ LANGUAGE plpgsql;

-- 触发器: trigger_update_tag_usage_count
-- 绑定: 将 `update_tag_usage_count` 函数绑定到 `post_tags_junction` 表上
-- 时机: 在 `post_tags_junction` 表中 每当有行被插入或删除之后 (AFTER INSERT OR DELETE), 
--        为每一行 (FOR EACH ROW) 都会自动执行一次 `update_tag_usage_count` 函数
DROP TRIGGER IF EXISTS trigger_update_tag_usage_count ON post_tags_junction;
CREATE TRIGGER trigger_update_tag_usage_count
AFTER INSERT OR DELETE ON post_tags_junction
FOR EACH ROW EXECUTE FUNCTION update_tag_usage_count();

-- -------------------------------------------------------------------
-- T.2: 自动为全文搜索生成和更新索引向量
-- -------------------------------------------------------------------

-- 函数: update_search_vector()
-- 职责: 此函数收由 C# 应用层传入的、已经分好词并用空格隔开的文本, 
--      然后使用 'simple' 配置将其高效地转换为 tsvector 格式
--      'simple' 配置在这里非常合适, 因为它能正确处理空格分隔的词汇
--      此函数会在插入新行, 或者在更新时 title_tokenized 或 content_tokenized 列发生变化时, 重新计算 search_vector
CREATE OR REPLACE FUNCTION update_search_vector()
RETURNS TRIGGER AS $$
BEGIN
    -- 判断触发条件:
    -- 1. 如果是 INSERT 操作 (TG_OP = 'INSERT'), 则无条件执行
    -- 2. 如果是 UPDATE 操作 (TG_OP = 'UPDATE'), 则仅当 title_tokenized 或 content_tokenized 的值发生改变时才执行
    --    使用 `IS DISTINCT FROM` 来比较新旧值, 它可以正确处理 NULL 值, 比 `!=` 更健壮
    IF (TG_OP = 'INSERT') OR 
       (TG_OP = 'UPDATE' AND 
           (NEW.title_tokenized IS DISTINCT FROM OLD.title_tokenized OR
            NEW.content_tokenized IS DISTINCT FROM OLD.content_tokenized)
       )
    THEN
        -- to_tsvector 的输入源为 tokenized 列
        -- 使用 'simple' 配置, 因为它能完美处理已经用空格分好词的文本
        -- 它会把 "我 爱 lunarium" 转换成 {'我', '爱', 'lunarium'} 的 tsvector
        NEW.search_vector := 
            setweight(to_tsvector('simple', COALESCE(NEW.title_tokenized, '')), 'A') || 
            setweight(to_tsvector('simple', COALESCE(NEW.content_tokenized, '')), 'B');
    END IF;

    RETURN NEW; -- 对于 BEFORE 触发器, 必须返回 NEW 以便将修改后的行写入表中
END;
$$ LANGUAGE plpgsql;

-- 触发器: trigger_update_search_vector (保持不变)
-- 绑定: 仍然绑定到 `posts_main` 表的 INSERT 或 UPDATE 事件上
-- 时机: BEFORE
DROP TRIGGER IF EXISTS trigger_update_search_vector ON posts_main;
CREATE TRIGGER trigger_update_search_vector
BEFORE INSERT OR UPDATE ON posts_main
FOR EACH ROW EXECUTE FUNCTION update_search_vector();

-- -------------------------------------------------------------------
-- T.3: 当频道被删除时, 软删除其下的所有帖子
-- -------------------------------------------------------------------

-- 函数: handle_channel_soft_delete()
-- 职责: 当一个频道 (channel) 从 `channels` 表中被删除时, 此函数会被触发
--        它不会级联删除帖子, 而是将 `posts_main` 表中所有属于该频道的帖子的
--        `is_deleted` 状态标记为 TRUE, 并清空其搜索相关的数据, 以实现“软删除”
--        这样做可以保留帖子的历史记录, 同时让它们在应用中不再可见或可搜索
CREATE OR REPLACE FUNCTION handle_channel_soft_delete()
RETURNS TRIGGER AS $$
BEGIN
    -- OLD 变量代表在 `channels` 表中被删除的那一行数据
    -- 我们用它的 channel_id 来找到所有需要被软删除的帖子
    UPDATE posts_main
    SET 
        is_deleted = TRUE,
        is_valid = FALSE, -- 逻辑上, 被删除的帖子也应该是无效的
        delete_at = NOW() -- 记录一下软删除的时间
    WHERE channel_id = OLD.channel_id; -- 关键的关联条件

    -- 对于 AFTER DELETE 触发器, 返回值通常是 NULL, 因为它不修改正在操作的行
    RETURN NULL; 
END;
$$ LANGUAGE plpgsql;

-- 触发器: trigger_channel_soft_delete_posts
-- 绑定: 将 `handle_channel_soft_delete` 函数绑定到 `channels` 表上
-- 时机: 在 `channels` 表的每一行被删除之后 (AFTER DELETE), 
--        为每一行 (FOR EACH ROW) 都会自动执行一次 `handle_channel_soft_delete` 函数
DROP TRIGGER IF EXISTS trigger_channel_soft_delete_posts ON channels;
CREATE TRIGGER trigger_channel_soft_delete_posts
AFTER DELETE ON channels
FOR EACH ROW EXECUTE FUNCTION handle_channel_soft_delete();

-- -------------------------------------------------------------------
-- T.4: 当帖子被软删除时, 级联处理其关联数据
-- -------------------------------------------------------------------

-- 函数: handle_post_soft_delete()
-- 职责: 监视 `posts_main` 表当一个帖子的 `is_deleted` 字段从 FALSE 变为 TRUE 时, 
--        此函数会自动触发, 执行一系列清理工作：
--        1. 软删除 `message_main` 中所有与该帖子相关的消息记录
--        2. 从 `post_tags_junction` 中删除该帖子的所有标签关系
--        3. 从 `post_members` 中删除该帖子的所有成员记录
--        这确保了数据的一致性, 避免了因帖子被软删除而产生的“孤儿”数据
CREATE OR REPLACE FUNCTION handle_post_soft_delete()
RETURNS TRIGGER AS $$
BEGIN
    -- 我们只关心更新(UPDATE)操作, 并且只有在 `is_deleted` 从 FALSE 变为 TRUE 时才执行
    -- `OLD.is_deleted = FALSE AND NEW.is_deleted = TRUE` 这个条件是核心！
    IF (TG_OP = 'UPDATE' AND OLD.is_deleted = FALSE AND NEW.is_deleted = TRUE) THEN
        
        -- 1. 软删除 message_main 中所有关联的消息
        UPDATE message_main
        SET is_deleted = TRUE
        WHERE thread_id = NEW.thread_id; -- NEW.thread_id 是被软删除的帖子的 ID

        -- 2. 从 post_tags_junction 删除所有标签关系
        --    因为帖子已经“消失”了, 所以它的标签关系也应该被清理掉
        DELETE FROM post_tags_junction
        WHERE thread_id = NEW.thread_id;

        -- 3. 从 post_members 删除所有成员关系
        --    同样, 帖子的成员列表也需要被清理
        DELETE FROM post_members
        WHERE thread_id = NEW.thread_id;

    END IF;

    -- 对于 AFTER 触发器, 返回值会被忽略
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- 触发器: trigger_post_soft_delete_cascade
-- 绑定: 将 `handle_post_soft_delete` 函数绑定到 `posts_main` 表上
-- 时机: 在 `posts_main` 表的每一行数据被更新之后 (AFTER UPDATE), 
--       都会自动执行一次上面的函数
DROP TRIGGER IF EXISTS trigger_post_soft_delete_cascade ON posts_main;
CREATE TRIGGER trigger_post_soft_delete_cascade
AFTER UPDATE ON posts_main
FOR EACH ROW EXECUTE FUNCTION handle_post_soft_delete();


-- -------------------------------------------------------------------
-- T.5: 收藏贴更新推送触发器
-- 描述: 当帖子更新时, 查找收藏了该贴且开启推送的用户, 写入 user_favorite_push_list
-- -------------------------------------------------------------------

CREATE OR REPLACE FUNCTION notify_favorites_on_post_update()
RETURNS TRIGGER AS $$
BEGIN
    -- 条件: 仅在 UPDATE 且 updated_at 发生变化, 且帖子未被软删除时触发
    IF (TG_OP = 'UPDATE' AND 
        NEW.updated_at IS DISTINCT FROM OLD.updated_at AND 
        NEW.is_deleted = FALSE) THEN

        INSERT INTO user_favorite_push_list (user_id, thread_id)
        SELECT 
            ufp.user_id,
            NEW.thread_id
        FROM 
            user_favorite_posts AS ufp
        WHERE 
            ufp.thread_id = NEW.thread_id
            AND ufp.allow_push = TRUE -- 仅推送开启了通知的用户
        
        -- 如果队列中已存在该记录, 什么都不做（保持在队列中即可）
        ON CONFLICT (user_id, thread_id) DO NOTHING;
            
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_notify_favorites ON posts_main;
CREATE TRIGGER trigger_notify_favorites
AFTER UPDATE ON posts_main
FOR EACH ROW EXECUTE FUNCTION notify_favorites_on_post_update();

-- -------------------------------------------------------------------
-- T.6: 作者订阅推送触发器
-- 描述: 当作者发布新帖(INSERT)或其帖子更新(UPDATE)时, 通知订阅该作者的用户
-- -------------------------------------------------------------------

CREATE OR REPLACE FUNCTION notify_author_subscribers()
RETURNS TRIGGER AS $$
DECLARE
    v_is_update BOOLEAN;
    -- 定义一个阈值, 例如 10 分钟
    -- 如果帖子创建时间比当前入库时间早 10 分钟以上, 说明是扫描器在补旧数据, 不是实时监听到的新帖
    v_time_threshold INTERVAL := '10 minutes'; 
BEGIN
    -- 预先判断操作类型和有效性
    IF (NEW.is_deleted = TRUE) THEN
        RETURN NULL;
    END IF;

    -- 判断是新帖还是更新
    IF (TG_OP = 'INSERT') THEN
        -- 检查这是否真的是"新"帖
        -- 如果当前时间 减去 帖子创建时间 > 阈值, 则视为历史数据入库, 不推送
        IF (NOW() - NEW.created_at > v_time_threshold) THEN
            RETURN NULL;
        END IF;
        
        v_is_update := FALSE;
        
    ELSIF (TG_OP = 'UPDATE' AND NEW.updated_at IS DISTINCT FROM OLD.updated_at) THEN
        v_is_update := TRUE;
    ELSE
        RETURN NULL;
    END IF;
    -- 插入推送队列
    INSERT INTO user_subscriptions_push_list (user_id, thread_id, author_id, is_update)
    SELECT 
        usa.user_id,
        NEW.thread_id,
        NEW.author_id,
        v_is_update
    FROM 
        user_subscriptions_author AS usa
    WHERE 
        usa.author_id = NEW.author_id
    
    -- 冲突处理:
    -- 如果同一个帖子已经在推送队列中：
    -- 1. 如果原本是 '新帖通知'(False), 现在来了 '更新通知'(True) -> 保持 '新帖通知' (False) 优先级更高, 或者视需求而定
    --    通常来说, 如果是新帖, 用户还没看, 后来又更新了, 用户只要知道是新帖就行
    -- 2. 如果原本是 '更新通知', 现在又是 '更新通知' -> 保持即可
    -- 这里选择：如果已存在, 更新 is_update 状态
    -- 但为了保留"这是一篇新帖"的状态(False), 只在原本是 True 的情况下才允许被覆盖(虽然 INSERT 不会覆盖 UPDATE, 但逻辑上严谨一点)
    ON CONFLICT (user_id, thread_id) DO UPDATE
    SET is_update = LEAST(user_subscriptions_push_list.is_update, EXCLUDED.is_update);
    -- 解释 LEAST(boolean, boolean): False < True
    -- 如果旧值是 False (新帖), 新值是 True (更新), 结果为 False (保留新帖状态)
    -- 如果旧值是 True, 新值是 False (理论上不可能发生), 结果为 False
    
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_notify_author_subs ON posts_main;
CREATE TRIGGER trigger_notify_author_subs
AFTER INSERT OR UPDATE ON posts_main
FOR EACH ROW EXECUTE FUNCTION notify_author_subscribers();

-- -------------------------------------------------------------------
-- T.7: 收藏夹名字同步器
-- 描述: 当用户重命名 user_favorite_types 中的收藏夹的时候, 自动更新 user_favorite_posts 中的收藏夹名字
-- -------------------------------------------------------------------

CREATE OR REPLACE FUNCTION sync_favorite_type_name_change()
RETURNS TRIGGER AS $$
BEGIN
    -- 检查 type_name 是否确实发生了改变
    -- 使用 IS DISTINCT FROM 可以安全处理 NULL
    IF (NEW.type_name IS DISTINCT FROM OLD.type_name) THEN
        
        -- 更新子表 user_favorite_posts
        -- 条件: favorite_as (外键) 等于当前更新行的 favorite_id (主键)
        UPDATE user_favorite_posts
        SET favorite_type_name = NEW.type_name
        WHERE favorite_as = NEW.favorite_id;
        
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_sync_favorite_type_name ON user_favorite_types;

CREATE TRIGGER trigger_sync_favorite_type_name
AFTER UPDATE OF type_name ON user_favorite_types
FOR EACH ROW
EXECUTE FUNCTION sync_favorite_type_name_change();

-- ===================================================================
-- T.8: 收藏夹计数自动维护器
-- 描述: 自动增减 user_favorite_types 中的 post_count
-- ===================================================================

CREATE OR REPLACE FUNCTION maintain_favorite_post_count()
RETURNS TRIGGER AS $$
BEGIN
    -- 情况 1: 新增收藏 (INSERT)
    IF (TG_OP = 'INSERT') THEN
        UPDATE user_favorite_types
        SET post_count = post_count + 1
        WHERE favorite_id = NEW.favorite_as;

    -- 情况 2: 删除收藏 (DELETE)
    ELSIF (TG_OP = 'DELETE') THEN
        UPDATE user_favorite_types
        SET post_count = post_count - 1
        WHERE favorite_id = OLD.favorite_as;

    -- 情况 3: 修改收藏分类 (UPDATE)
    -- 只有当 favorite_as (归属的收藏夹ID) 发生变化时才处理
    ELSIF (TG_OP = 'UPDATE' AND OLD.favorite_as IS DISTINCT FROM NEW.favorite_as) THEN
        -- 旧收藏夹数量 -1
        UPDATE user_favorite_types
        SET post_count = post_count - 1
        WHERE favorite_id = OLD.favorite_as;
        
        -- 新收藏夹数量 +1
        UPDATE user_favorite_types
        SET post_count = post_count + 1
        WHERE favorite_id = NEW.favorite_as;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- 删除旧触发器以防重复定义
DROP TRIGGER IF EXISTS trigger_maintain_favorite_count ON user_favorite_posts;
-- 创建触发器
-- 这里要监听 INSERT, DELETE 以及 UPDATE (仅当 favorite_as 字段变动时)
CREATE TRIGGER trigger_maintain_favorite_count
AFTER INSERT OR DELETE OR UPDATE OF favorite_as ON user_favorite_posts
FOR EACH ROW
EXECUTE FUNCTION maintain_favorite_post_count();