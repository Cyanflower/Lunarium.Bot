-- 表: tags
-- 描述: 存储唯一标签
CREATE TABLE IF NOT EXISTS tags (
    tag_id BIGINT PRIMARY KEY,
    channel_id BIGINT NOT NULL,
    tag_name TEXT NOT NULL,
    channel_name TEXT,
    guild_name TEXT,
    usage_count INT NOT NULL DEFAULT 0,
    
